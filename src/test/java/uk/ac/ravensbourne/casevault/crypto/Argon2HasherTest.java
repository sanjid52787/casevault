package uk.ac.ravensbourne.casevault.crypto;

import static org.junit.jupiter.api.Assertions.*;

import java.nio.file.Files;
import java.nio.file.Path;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.springframework.security.crypto.password.PasswordEncoder;
import uk.ac.ravensbourne.casevault.config.SecurityConfiguration;

class Argon2HasherTest {

    @Test
    void tCrypto003Argon2HasherDerivesConfigurationFromPasswordEncoder(@TempDir Path tempDir) throws Exception {
        Path secretFile = tempDir.resolve("secret.txt");
        Path outputFile = tempDir.resolve("hash.txt");
        String plain = "AComplexSecretP@ssw0rd123!";
        Files.writeString(secretFile, plain);

        Argon2Hasher.main(new String[]{secretFile.toString(), outputFile.toString()});

        assertTrue(Files.exists(outputFile), "Hash output file must be created");
        String hash = Files.readString(outputFile).trim();

        // Must match Argon2id parameters configured in SecurityConfiguration (m=19456, t=3, p=1)
        assertTrue(hash.startsWith("$argon2id$v=19$m=19456,t=3,p=1$"), "Hash must use Spring Security Argon2id baseline");

        PasswordEncoder encoder = new SecurityConfiguration().passwordEncoder();
        assertTrue(encoder.matches(plain, hash), "Hash generated by Argon2Hasher must verify with SecurityConfiguration bean");
        assertFalse(encoder.matches("WrongPassword", hash), "Hash must reject invalid password");
    }

    @Test
    void tCrypto004Argon2HasherRejectsMissingOrEmptyFile(@TempDir Path tempDir) throws Exception {
        Path missing = tempDir.resolve("non-existent.txt");
        assertThrows(IllegalArgumentException.class, () -> Argon2Hasher.main(new String[]{missing.toString()}));

        Path empty = tempDir.resolve("empty.txt");
        Files.writeString(empty, "   \n");
        assertThrows(IllegalArgumentException.class, () -> Argon2Hasher.main(new String[]{empty.toString()}));
    }
}

